/// The built-in grocery catalog: every tile on the shopping screen, and the
/// shared vocabulary the pantry inventory and Gemini meal planning will use
/// later -- each item already knows where it's stored and roughly how long
/// it keeps, so "bought" can turn into "in the fridge until Friday".
library;

enum StorageLocation { pantry, fridge, freezer, household }

enum GroceryCategory {
  fruitVeg('Fruit & veg', 0xFF4CAF50),
  bakery('Bakery', 0xFFD9A066),
  dairy('Dairy & eggs', 0xFF64B5F6),
  meatFish('Meat & fish', 0xFFE57373),
  pantry('Pantry', 0xFFFFB74D),
  frozen('Frozen', 0xFF4DD0E1),
  drinks('Drinks', 0xFF9575CD),
  snacks('Snacks & sweets', 0xFFF06292),
  household('Household', 0xFF90A4AE),
  personal('Personal care', 0xFFA1887F),
  other('Other', 0xFF78909C);

  const GroceryCategory(this.label, this.colorValue);

  final String label;
  final int colorValue;
}

class CatalogItem {
  const CatalogItem(
    this.id,
    this.name,
    this.emoji,
    this.category, {
    this.storage = StorageLocation.pantry,
    this.shelfLifeDays,
    this.aliases = const [],
  });

  final String id;
  final String name;
  final String emoji;
  final GroceryCategory category;

  /// Where it usually lives once bought -- for the pantry inventory.
  final StorageLocation storage;

  /// Rough days it keeps once bought; null for things that don't go off
  /// (household, personal care). Starting point for inventory expiry dates.
  final int? shelfLifeDays;

  /// Other names to search by, mainly German as seen on shop shelves.
  final List<String> aliases;
}


final Map<String, CatalogItem> kCatalogById = {
  for (final item in kCatalog) item.id: item,
};

String _fold(String s) => s
    .toLowerCase()
    .replaceAll('ä', 'a')
    .replaceAll('ö', 'o')
    .replaceAll('ü', 'u')
    .replaceAll('ß', 'ss')
    .trim();

/// Catalog items matching [query] by name or alias, best matches first:
/// names that start with it, then aliases that start with it, then anything
/// containing it. German umlauts match their plain letters ("Apfel"/"Äpfel").
List<CatalogItem> searchCatalog(String query) {
  final q = _fold(query);
  if (q.isEmpty) return const [];
  int? rank(CatalogItem item) {
    final name = _fold(item.name);
    final aliases = item.aliases.map(_fold);
    if (name.startsWith(q)) return 0;
    if (aliases.any((a) => a.startsWith(q))) return 1;
    if (name.contains(q)) return 2;
    if (aliases.any((a) => a.contains(q))) return 3;
    return null;
  }

  final ranked = [
    for (final item in kCatalog)
      if (rank(item) case final r?) (r, item),
  ]..sort((a, b) => a.$1.compareTo(b.$1));
  return [for (final r in ranked) r.$2];
}

/// Id for an item the user typed that isn't in the catalog, so adding
/// "Dosa batter" twice is the same list entry, not two.
String customItemId(String name) =>
    'custom-${_fold(name).replaceAll(RegExp(r'[^a-z0-9]+'), '-').replaceAll(RegExp(r'^-+|-+$'), '')}';
